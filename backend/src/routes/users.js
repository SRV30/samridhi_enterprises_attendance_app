const express = require('express');
const bcrypt = require('bcryptjs');
const crypto = require('crypto');
const mongoose = require('mongoose');
const User = require('../models/User');
const Visit = require('../models/Visit');
const { authenticate, allowRoles } = require('../middleware/auth');

const router = express.Router();
router.use(authenticate, allowRoles('admin'));

function cleanPhone(value) {
  return value ? String(value).trim().replace(/[\\s().-]/g, '') : '';
}
function validEmail(value) {
  return typeof value === 'string' && /^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/.test(value);
}

// Admin can create either role. Internal employee IDs are generated by the server.
router.post('/', async (req, res, next) => {
  try {
    const { name, email, phone, password, role = 'employee' } = req.body || {};
    if (!['admin', 'employee'].includes(role)) return res.status(400).json({ message: 'Role must be admin or employee' });
    if (typeof name !== 'string' || !name.trim() || !validEmail(email) || typeof password !== 'string' || !password) {
      return res.status(400).json({ message: 'Name, valid email and password are required' });
    }
    if (Buffer.byteLength(password, 'utf8') > 72) return res.status(400).json({ message: 'Password must not exceed 72 bytes' });

    const normalizedEmail = email.trim().toLowerCase();
    const normalizedPhone = cleanPhone(phone);
    if (phone && !/^\\+?\\d{7,15}$/.test(normalizedPhone)) return res.status(400).json({ message: 'Enter a valid phone number with 7 to 15 digits' });
    if (await User.exists({ email: normalizedEmail })) return res.status(409).json({ message: 'An account with this email already exists' });

    const employeeId = (role === 'admin' ? 'ADM-' : 'EMP-') + crypto.randomBytes(6).toString('hex').toUpperCase();
    const passwordHash = await bcrypt.hash(password, 12);
    const user = await User.create({
      name: name.trim(), employeeId, email: normalizedEmail, phone: normalizedPhone,
      passwordHash, role, isDeleted: false
    });
    res.status(201).json({ user: {
      id: user.id, name: user.name, employeeId: user.employeeId, email: user.email,
      phone: user.phone || '', role: user.role, active: user.active, createdAt: user.createdAt
    } });
  } catch (error) { next(error); }
});

// Normal account directory excludes archived accounts.
router.get('/', async (_req, res, next) => {
  try {
    const users = await User.find({ isDeleted: { $ne: true } })
      .select('name employeeId email phone role active createdAt updatedAt')
      .sort({ role: 1, name: 1 }).lean();
    res.setHeader('Cache-Control', 'no-store');
    res.json({ users });
  } catch (error) { next(error); }
});

// Full profile and attendance history summary for the admin viewer.
router.get('/:id/profile', async (req, res, next) => {
  try {
    if (!mongoose.isValidObjectId(req.params.id)) return res.status(400).json({ message: 'Invalid account ID' });
    const profile = await User.findById(req.params.id)
      .select('name employeeId email phone role active isDeleted deletedAt createdAt updatedAt').lean();
    if (!profile) return res.status(404).json({ message: 'Account not found' });
    const filter = { employee: profile._id };
    const [totalVisits, days, recentVisits] = await Promise.all([
      Visit.countDocuments(filter),
      Visit.distinct('attendanceDay', filter),
      Visit.find(filter).populate('shop', 'name shopCode address area').sort({ checkedInAt: -1 }).limit(100).lean()
    ]);
    res.setHeader('Cache-Control', 'no-store');
    res.json({ profile: { ...profile, totalVisits, presentDays: days.length, recentVisits, recentVisitsLimit: 100 } });
  } catch (error) { next(error); }
});

// Deactivate/reactivate employees. Admin account state is protected here.
router.patch('/:id', async (req, res, next) => {
  try {
    if (!mongoose.isValidObjectId(req.params.id)) return res.status(400).json({ message: 'Invalid user ID' });
    const body = req.body || {};
    if (Object.keys(body).length !== 1 || typeof body.active !== 'boolean') return res.status(400).json({ message: 'Only an active boolean can be updated' });
    const user = await User.findById(req.params.id);
    if (!user || user.isDeleted) return res.status(404).json({ message: 'Account not found' });
    if (user.role !== 'employee') return res.status(403).json({ message: 'Only employee accounts can be deactivated here' });
    user.active = body.active;
    await user.save();
    res.json({ user: { id: user.id, name: user.name, employeeId: user.employeeId, email: user.email, phone: user.phone || '', role: user.role, active: user.active } });
  } catch (error) { next(error); }
});

// Archive an account. This revokes sign-in but preserves the record and its attendance trail.
router.post('/:id/archive', async (req, res, next) => {
  try {
    if (!mongoose.isValidObjectId(req.params.id)) return res.status(400).json({ message: 'Invalid account ID' });
    if (String(req.user.id) === String(req.params.id)) return res.status(403).json({ message: 'You cannot archive the admin account you are currently using' });
    const user = await User.findById(req.params.id);
    if (!user || user.isDeleted) return res.status(404).json({ message: 'Account not found' });
    if (user.role === 'admin' && user.active) {
      const admins = await User.countDocuments({ role: 'admin', active: true, isDeleted: { $ne: true } });
      if (admins <= 1) return res.status(409).json({ message: 'The last active admin account cannot be archived' });
    }
    user.active = false;
    user.isDeleted = true;
    user.deletedAt = new Date();
    await user.save();
    res.json({ message: 'Account archived. Sign-in is disabled and attendance history is retained.' });
  } catch (error) { next(error); }
});

module.exports = router;
